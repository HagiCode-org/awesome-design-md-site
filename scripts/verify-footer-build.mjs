import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const siteOrigin = new URL(process.env.SITE_URL ?? 'https://design.hagicode.com').origin;
const hagilightFaviconUrl = 'https://cdn.jsdelivr.net/npm/@hagicode/hagilight-core@0.5.0/favicon.ico';
const locales = ['en', 'zh-CN', 'zh-Hant', 'ja-JP', 'ko-KR', 'de-DE', 'fr-FR', 'es-ES', 'pt-BR', 'ru-RU'];
const pages = [
  new URL('../dist/index.html', import.meta.url),
  new URL('../dist/zh-CN/index.html', import.meta.url),
];

async function assertEmptyFeed(filename, language) {
  const xml = await readFile(new URL(`../dist/${filename}`, import.meta.url), 'utf8');
  assert.match(xml, /^<\?xml/u, `${filename} must be XML`);
  const channel = xml.match(/<channel>([\s\S]*?)<\/channel>/u)?.[1];
  assert.ok(channel, `${filename} must contain an RSS channel`);
  assert.match(channel, /<title>[^<]+<\/title>/u, `${filename} needs a title`);
  assert.match(channel, /<description>[^<]+<\/description>/u, `${filename} needs a description`);
  assert.match(channel, new RegExp(`<language>${language}</language>`, 'u'));
  assert.ok(channel.includes(`<link>${new URL('/', siteOrigin).href}</link>`));
  assert.doesNotMatch(xml, /<item>/u, `${filename} should be the built-in empty feed`);
  return { channel, items: [...xml.matchAll(/<item>([\s\S]*?)<\/item>/gu)] };
}

for (const page of pages) {
  const html = await readFile(page, 'utf8');
  const isZhCn = page.pathname.includes('/zh-CN/');

  assert.equal([...html.matchAll(/<footer\b[^>]*class="[^"]*\bhagilight-footer\b[^"]*"/gu)].length, 1);
  // Hagilight groups footer links into purpose-based columns (`nav[data-column]`), so ecosystem sites
  // are no longer under their own heading. The site must not link to itself from a column (it identifies
  // itself with siteId), while other HagiCode sites stay listed. The feeds nav links to this site's own
  // RSS and sitemap, so it is deliberately left out.
  const footer = html.match(/<footer\b[^>]*class="[^"]*\bhagilight-footer\b[^"]*"[\s\S]*?<\/footer>/u)?.[0] ?? '';
  const columns = [...footer.matchAll(/<nav\b[^>]*\bdata-column="[^"]+"[^>]*>[\s\S]*?<\/nav>/gu)].map((match) => match[0]);
  assert.ok(columns.length > 0, 'The footer must render its link columns');
  const relatedHosts = columns
    .flatMap((column) => [...column.matchAll(/<a href="(https?:\/\/[^"]+)"/gu)])
    .map((match) => new URL(match[1]).host);
  assert.ok(relatedHosts.includes('www.hagicode.com'), 'Footer columns must list other HagiCode sites');
  assert.ok(!relatedHosts.includes(new URL(siteOrigin).host), 'Footer columns must not list this site itself');
  const icons = [...html.matchAll(/<link\b[^>]*\brel="icon"[^>]*>/gu)];
  assert.equal(icons.length, 1);
  assert.ok(icons[0][0].includes(`href="${hagilightFaviconUrl}"`));
  // RSS feeds are now auto-generated by hagilight() without external handling,
  // and the Footer renders a link to the generated feed.
  assert.ok(html.includes(new URL('rss.xml', siteOrigin).href));
  if (isZhCn) {
    assert.ok(html.includes(new URL('rss.zh-CN.xml', siteOrigin).href));
  }
}

const rootFeed = await assertEmptyFeed('rss.xml', 'en');
const englishAlias = await assertEmptyFeed('rss.en.xml', 'en');
assert.equal(englishAlias.channel, rootFeed.channel, 'English alias must retain root-feed metadata');
for (const locale of locales.filter((value) => value !== 'en')) {
  await assertEmptyFeed(`rss.${locale}.xml`, locale);
}

const robots = await readFile(new URL('../dist/robots.txt', import.meta.url), 'utf8');
const sitemap = await readFile(new URL('../dist/sitemap-index.xml', import.meta.url), 'utf8');
assert.ok(robots.includes(`Sitemap: ${siteOrigin}/sitemap-index.xml`));
assert.ok(sitemap.includes(`${siteOrigin}/sitemap-0.xml`));